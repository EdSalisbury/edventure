	org $2000
        icl "hardware.s"

chr = $2400
num_chars = 7
screen = $4000

init
        mwa #dlist SDLSTL

; Use custom character set
        mva #>chr CHBAS

        ldy #0
        ldx #0
next_line
        lda charset, y
        sta chr, x
        inx
        iny
        cpy #(8 * num_chars)
        bne next_line

; Main Loop
        jsr vblank

        ldx #0
map_copy
        mva map,x screen,x
        mva map+$100,x screen+$100,x
        mva map+$200,x screen+$200,x
        inx
        bne map_copy

        jmp *

vblank
        pha
        mva #$80 $2c4
        mva #$86 $2c5
        mva #$8a $2c6

        lda #1
        sta 540
vblank_loop
        lda 540
        bne vblank_loop
        pla
        rts

dlist
